#!/usr/bin/env python3
# Generates kernel/font.h (8x16 bitmap font, ASCII 32..126) from DejaVu Sans Mono.
from PIL import Image, ImageDraw, ImageFont
import sys
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
f = ImageFont.truetype(path, 13)
out = ["// generated by tools/genfont.py", "static const unsigned char font8x16[95][16] = {"]
for ch in range(32, 127):
    im = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), chr(ch), font=f, fill=255)
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 100:
                b |= 0x80 >> x
        rows.append("0x%02X" % b)
    out.append("  {" + ",".join(rows) + "},")
out.append("};")
open("kernel/font.h", "w").write("\n".join(out) + "\n")
